def get_config(word: str) -> dict:
    """Получить конфигурацию для слова по ключу (siesta, votchi, miku, smith)."""
    if word not in CONFIGS:
        raise ValueError(f"Unknown word '{word}'. Available: {list(CONFIGS.keys())}")
    cfg = dict(CONFIGS[word])
    cfg["key"] = word
    # Класс 2 — кастомное слово, класс 1 — алиса
    cfg["classes"] = ["filler", "алиса", cfg["word_ru"]]
    cfg["kind2cls"] = {"pos_alisa": 1, f"pos_{word}": 2, "sent_alisa": 1, f"sent_{word}": 2}
    # Объединённый список негативов: специфичные + общие
    cfg["all_neg_words"] = list(cfg["neg_words"]) + COMMON_NEG_WORDS
    # Директория по умолчанию
    cfg["default_raw_dir"] = word
    return cfg


def list_words() -> list:
    """Вернуть список доступных слов."""
    return list(CONFIGS.keys())


if __name__ == "__main__":
    import argparse, json
    ap = argparse.ArgumentParser(description="Конфигурация wake-word моделей")
    ap.add_argument("--word", choices=list(CONFIGS.keys()), help="Вывести конфигурацию слова")
    ap.add_argument("--list", action="store_true", help="Список доступных слов")
    a = ap.parse_args()
    if a.list:
        for w in CONFIGS:
            print(f"  {w}: {CONFIGS[w]['word_ru']}")
    elif a.word:
        print(json.dumps(get_config(a.word), ensure_ascii=False, indent=2))
    else:
        ap.print_help()
